values('submission-media','submission-media',true,104857600,array['video/mp4','video/webm','image/jpeg','image/png','image/webp'])
on conflict(id) do nothing;

drop policy if exists "Public read submission media" on storage.objects;
create policy "Public read submission media" on storage.objects for select using (bucket_id='submission-media');
drop policy if exists "Users upload own media" on storage.objects;
create policy "Users upload own media" on storage.objects for insert to authenticated
with check (bucket_id='submission-media' and (storage.foldername(name))[1]=auth.uid()::text);

