create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  author_name text not null default 'Участник',
  title text not null check (char_length(title) between 1 and 90),
  description text default '',
  url text,
  file_url text,
  file_type text,
  category text not null default 'Видео',
  type text not null default 'media' check (type in ('media','question')),
  status text not null default 'pending' check (status in ('pending','watched','rejected')),
  votes_count integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  submission_id bigint not null references public.submissions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(submission_id,user_id)
);

alter table public.profiles enable row level security;
alter table public.submissions enable row level security;
alter table public.votes enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and is_admin=true); $$;

drop policy if exists "Profiles readable by owner" on public.profiles;
create policy "Profiles readable by owner" on public.profiles for select using (id=auth.uid() or public.is_admin());
drop policy if exists "Users create own profile" on public.profiles;
create policy "Users create own profile" on public.profiles for insert with check (id=auth.uid());
drop policy if exists "Submissions visible" on public.submissions;
create policy "Submissions visible" on public.submissions for select using (status in ('pending','watched') or public.is_admin());
drop policy if exists "Authenticated users submit" on public.submissions;
create policy "Authenticated users submit" on public.submissions for insert with check (auth.uid() is not null and user_id=auth.uid());
drop policy if exists "Admins update submissions" on public.submissions;
create policy "Admins update submissions" on public.submissions for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Users read votes" on public.votes;
create policy "Users read votes" on public.votes for select using (true);
drop policy if exists "Users vote once" on public.votes;
create policy "Users vote once" on public.votes for insert with check (auth.uid()=user_id);

-- Счётчик голосов автоматически пересчитывается триггером.
create or replace function public.refresh_vote_count()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  update public.submissions
  set votes_count=(select count(*) from public.votes where submission_id=coalesce(new.submission_id,old.submission_id))
  where id=coalesce(new.submission_id,old.submission_id);
  return coalesce(new,old);
end; $$;
drop trigger if exists votes_count_trigger on public.votes;
create trigger votes_count_trigger after insert or delete on public.votes
for each row execute function public.refresh_vote_count();

-- Создание профиля после регистрации.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id,display_name) values(new.id,coalesce(new.raw_user_meta_data->>'display_name',split_part(new.email,'@',1)));
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

-- Файловое хранилище: публичное чтение, загрузка только в личную папку.
